import fs from "fs/promises";
import path from "path";
import { PDFDocument, StandardFonts, rgb, type PDFPage, type PDFFont } from "pdf-lib";
import type { AgreementRenterRow } from "./multi-tenant-signatures";

const FOOTER_TEXT = "Generated by https://sharehousemanagers.com";

export type ImportedPdfBrandingOptions = {
  renters?: AgreementRenterRow[];
  landlord?: AgreementRenterRow | null;
};

/** Hide the imported template's top owner/landlord name line (e.g. "Name: …") — not the PMC block below. */
function eraseImportedTopOwnerNameLine(page: PDFPage, width: number, height: number) {
  page.drawRectangle({
    x: 24,
    y: height - 72,
    width: width - 48,
    height: 16,
    color: rgb(1, 1, 1),
    borderWidth: 0,
  });
}

/**
 * Replace the template's single-renter block under the existing
 * "The Renters (Co-renter(s) or Sub-Renter)" heading (right column, page 1).
 * Does not add overlays at the top of the page.
 */
function drawRentersInTemplateSection(
  page: PDFPage,
  font: PDFFont,
  renters: AgreementRenterRow[],
  width: number,
  height: number,
) {
  if (!renters.length) return;

  const margin = 28;
  const colLeft = width / 2 + 8;
  const blockWidth = width - colLeft - margin;
  const lineHeight = 12;
  const blockHeight = Math.min(240, 28 + renters.length * (lineHeight * 2 + 10));
  // Right column — under the printed "The Renters" heading (eSignatures import layout).
  const sectionAnchorY = height * 0.545;
  const blockBottom = sectionAnchorY - blockHeight;
  const textStartY = sectionAnchorY - 6;

  page.drawRectangle({
    x: colLeft - 8,
    y: blockBottom,
    width: blockWidth + 12,
    height: blockHeight,
    color: rgb(1, 1, 1),
    borderWidth: 0,
  });

  let y = textStartY;
  renters.forEach((renter, index) => {
    if (index > 0) y -= 6;
    page.drawText(`Name Renter : ${renter.name}`, {
      x: colLeft,
      y,
      size: 9,
      font,
      color: rgb(0.12, 0.14, 0.16),
    });
    y -= lineHeight;
    page.drawText(`Email: ${renter.email}`, {
      x: colLeft,
      y,
      size: 9,
      font,
      color: rgb(0.12, 0.14, 0.16),
    });
    y -= lineHeight + 2;
  });
}

async function loadShmLogo(pdf: PDFDocument) {
  const candidates = [
    path.join(process.cwd(), "public", "shm-logo.png"),
    path.join(process.cwd(), "public", "shm-plugin-assets", "images", "tenant-agreement-header.png"),
  ];
  for (const candidate of candidates) {
    try {
      const bytes = await fs.readFile(candidate);
      return pdf.embedPng(bytes);
    } catch {
      // try next
    }
  }
  return null;
}

/** Remove eSignatures header/footer branding from imported agreement PDFs. */
export async function applyShmBrandingToImportedPdfBuffer(
  pdfBytes: Buffer,
  options?: ImportedPdfBrandingOptions,
): Promise<Buffer> {
  try {
    return await applyShmBrandingToImportedPdfBufferInner(pdfBytes, options);
  } catch (error) {
    console.error("[tenant-agreement-pdf-branding]", error instanceof Error ? error.message : error);
    return pdfBytes;
  }
}

async function applyShmBrandingToImportedPdfBufferInner(
  pdfBytes: Buffer,
  options?: ImportedPdfBrandingOptions,
): Promise<Buffer> {
  const pdf = await PDFDocument.load(pdfBytes, { ignoreEncryption: true });
  const pages = pdf.getPages();
  if (!pages.length) return pdfBytes;

  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const logo = await loadShmLogo(pdf);
  const total = pages.length;
  const footerColor = rgb(0.45, 0.45, 0.45);
  const renters = options?.renters || [];

  pages.forEach((page, index) => {
    const { width, height } = page.getSize();

    page.drawRectangle({
      x: 0,
      y: height - 48,
      width: 130,
      height: 48,
      color: rgb(1, 1, 1),
      borderWidth: 0,
    });

    if (logo) {
      const logoWidth = Math.min(120, width * 0.22);
      const logoHeight = (logo.height / logo.width) * logoWidth;
      page.drawImage(logo, {
        x: width - logoWidth - 28,
        y: height - logoHeight - 10,
        width: logoWidth,
        height: logoHeight,
      });
    }

    const footerHeight = 42;
    page.drawRectangle({
      x: 0,
      y: 0,
      width,
      height: footerHeight,
      color: rgb(1, 1, 1),
      borderWidth: 0,
    });

    page.drawText(FOOTER_TEXT, {
      x: 28,
      y: 14,
      size: 8,
      font,
      color: footerColor,
    });

    const pageLabel = `Page ${index + 1}/${total}`;
    const labelWidth = font.widthOfTextAtSize(pageLabel, 8);
    page.drawText(pageLabel, {
      x: Math.max(28, width / 2 - labelWidth / 2),
      y: 14,
      size: 8,
      font,
      color: footerColor,
    });

    if (index === 0) {
      eraseImportedTopOwnerNameLine(page, width, height);
      if (renters.length >= 1) {
        drawRentersInTemplateSection(page, font, renters, width, height);
      }
    }
  });

  return Buffer.from(await pdf.save());
}
