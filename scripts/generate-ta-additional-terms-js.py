"""Generate ta-default-additional-terms.js from _rules_extract.txt."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
text = (ROOT / "scripts" / "_rules_extract.txt").read_text(encoding="utf-8")
start = text.find("11. Water consumption")
end = text.find("Additional Share House Rules")
section = text[start:end]
section = re.sub(r"===== PAGE \d+ =====\n", "", section)
section = re.sub(r"Page \d+/\d+\n", "", section)
section = re.sub(r"Omkar Lengare[^\n]*\n", "", section)
section = re.sub(r"Generated by https://esignatures.com[^\n]*\n", "", section)
parts = re.split(r"(?=\n(?:1[1-9]|[2-3][0-9]|4[0-4])\.\s)", "\n" + section.strip())
clauses = [re.sub(r"\s+", " ", p.strip()) for p in parts if p.strip()]
# OCR/PDF extract sometimes mangles "annually" — keep the legal wording correct.
clauses = [c.replace('checked data by', 'checked annually by') for c in clauses]

out = ROOT / "lib" / "shm" / "templates" / "ta-default-additional-terms.js"
lines = ["const TA_DEFAULT_ADDITIONAL_TERMS = ["]
for clause in clauses:
    lines.append("  " + json.dumps(clause, ensure_ascii=False) + ",")
lines.append("];")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")

public = ROOT / "public" / "shm-plugin-assets" / "templates" / "ta-default-additional-terms.js"
public.parent.mkdir(parents=True, exist_ok=True)
public.write_text(out.read_text(encoding="utf-8"), encoding="utf-8")
print(f"Wrote {len(clauses)} clauses to {out}")
